//! Erkennt Hinweise auf KI-Erzeugung in Metadaten, etwa C2PA-Herkunftsnachweise,
//! IPTC-Quelltypen, Prompts aus Stable Diffusion oder ComfyUI und Generatornamen.
//! Die Erkennung dient nur der Anzeige, entfernt wird ohnehin alles.

pub const LABEL: &str = "KI-Kennzeichnung (C2PA, Prompt, Generator)";

const MARKERS: &[&str] = &[
    "c2pa",
    "jumbf",
    "contentcredentials",
    "algorithmicmedia",
    "digitalsourcetype",
    "negative prompt",
    "parameters\0",
    "prompt\0",
    "workflow\0",
    "\"prompt\"",
    "steps: ",
    "midjourney",
    "dall-e",
    "dall·e",
    "openai",
    "chatgpt",
    "stable diffusion",
    "stablediffusion",
    "comfyui",
    "automatic1111",
    "novelai",
    "firefly",
    "synthid",
    "google ai",
    "gemini",
    "sora",
    "ideogram",
    "leonardo.ai",
    "flux.1",
    "grok",
    "made with ai",
    "ai generated",
    "ai-generated",
    "generated by ai",
];

pub fn marker(data: &[u8]) -> bool {
    let text = String::from_utf8_lossy(data).to_lowercase();
    MARKERS.iter().any(|m| text.contains(m))
}
