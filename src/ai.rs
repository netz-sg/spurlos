pub fn scan(data: &[u8]) -> impl Iterator<Item = &'static str> {
    let text = String::from_utf8_lossy(data).to_lowercase();
    SOURCES.iter().filter(move |(m, _)| text.contains(m)).map(|(_, name)| *name)
}
